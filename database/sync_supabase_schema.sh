#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

SCHEMA_FILE="supabase/schema.sql"
INDEXES_FILE="supabase/indexes.sql"

if ! command -v supabase >/dev/null 2>&1; then
  echo "ERROR: supabase CLI not found in PATH. Install it first (https://supabase.com/docs/guides/cli)." >&2
  exit 1
fi

mkdir -p "$(dirname "$SCHEMA_FILE")"

echo "Dumping schema to: $SCHEMA_FILE"
# Note: supabase CLI dumps from the linked remote DB by default.
supabase db dump --schema public -f "$SCHEMA_FILE"

echo "Splitting indexes into: $INDEXES_FILE"
echo "Stripping RLS/policies, owners/grants/comments (defense-in-depth) from: $SCHEMA_FILE"
python3 - <<'PY'
import pathlib
import re

path = pathlib.Path("supabase/schema.sql")
indexes_path = pathlib.Path("supabase/indexes.sql")
src = path.read_text(encoding="utf-8")

# Remove whole SQL statements starting with any of these (skip until semicolon).
statement_starters = (
    "CREATE INDEX",
    "CREATE UNIQUE INDEX",
    "ALTER TABLE",  # we'll selectively keep most; handle noisy ALTERs below
    "GRANT",
    "REVOKE",
    "COMMENT ON",
    "CREATE POLICY",
    "ALTER POLICY",
    "DROP POLICY",
)

noise_alter_regexes = [
    re.compile(r'^ALTER TABLE .* OWNER TO .*;$', re.IGNORECASE),
    re.compile(r'^ALTER TABLE .* ENABLE ROW LEVEL SECURITY;$', re.IGNORECASE),
    re.compile(r'^ALTER TABLE .* FORCE ROW LEVEL SECURITY;$', re.IGNORECASE),
    re.compile(r'^ALTER TABLE .* DISABLE ROW LEVEL SECURITY;$', re.IGNORECASE),
]

def is_index_stmt(stmt: str) -> bool:
    s = stmt.strip()
    return s.startswith("CREATE INDEX") or s.startswith("CREATE UNIQUE INDEX")

def is_noise_single_line(stmt: str) -> bool:
    s = stmt.strip()
    if not s:
        return False
    if s.startswith("GRANT") or s.startswith("REVOKE"):
        return True
    if s.startswith("COMMENT ON"):
        return True
    if s.startswith("CREATE POLICY") or s.startswith("ALTER POLICY") or s.startswith("DROP POLICY"):
        return True
    if s.startswith("ALTER TABLE"):
        return any(r.match(s) for r in noise_alter_regexes)
    return False

out_chunks = []
index_chunks = []
buf = []
in_stmt = False

def flush_stmt():
    global buf
    if not buf:
        return
    stmt = "".join(buf)
    if is_index_stmt(stmt):
        index_chunks.append(stmt)
        buf = []
        return
    if is_noise_single_line(stmt):
        buf = []
        return
    out_chunks.append(stmt)
    buf = []

for line in src.splitlines(keepends=True):
    stripped = line.lstrip()

    # Remove SQL comments entirely.
    if stripped.startswith("--"):
        continue

    # Detect statement boundaries: a very simple heuristic that works well for pg_dump output.
    if not in_stmt:
        # Start buffering only if the line seems like a DDL statement.
        if stripped and any(stripped.startswith(s) for s in statement_starters):
            in_stmt = True
            buf.append(line)
            if ";" in line:
                in_stmt = False
                flush_stmt()
            continue
        else:
            out_chunks.append(line)
            continue
    else:
        buf.append(line)
        if ";" in line:
            in_stmt = False
            flush_stmt()

# Flush any trailing partial statement (shouldn't happen, but be safe)
if buf:
    stmt = "".join(buf)
    if is_index_stmt(stmt):
        index_chunks.append(stmt)
    elif not is_noise_single_line(stmt):
        out_chunks.append(stmt)

clean = "".join(out_chunks)

# Extra: strip any leftover standalone OWNER/GRANT/REVOKE just in case.
clean = re.sub(r'(?mi)^ALTER .* OWNER TO .*;\s*$', "", clean)
clean = re.sub(r'(?mi)^(GRANT|REVOKE)\b.*;\s*$', "", clean)
clean = re.sub(r'(?mi)^COMMENT ON\b.*;\s*$', "", clean)
clean = re.sub(r'(?mi)^ALTER TABLE\b.*\b(ENABLE|FORCE|DISABLE)\s+ROW\s+LEVEL\s+SECURITY\s*;\s*$', "", clean)
clean = re.sub(r'(?mis)^CREATE POLICY\b.*?;\s*$', "", clean)

# Normalize excessive blank lines.
clean = re.sub(r"\n{4,}", "\n\n\n", clean)

path.write_text(clean, encoding="utf-8")

# Write indexes file (normalized, no comments, safe to run repeatedly because schema.sql uses CREATE OR REPLACE elsewhere)
indexes = "".join(index_chunks)
indexes = indexes.strip() + ("\n" if indexes.strip() else "")
indexes = re.sub(r"\n{4,}", "\n\n\n", indexes)
indexes_path.write_text(
    "-- Indexes extracted from Supabase schema dump\n"
    "-- This file is generated by supabase_db/sync_supabase_schema.sh\n\n"
    + indexes,
    encoding="utf-8",
)
PY


echo "Done."

